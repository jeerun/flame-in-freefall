def peer_url(address, path):
    # The CLI normalizes the configured origin. Callers supply fixed route literals.
    return address.rstrip("/") + path


def open_peer(server, path, timeout, data=None, content_type=None):
    headers = {"Content-Type": content_type} if content_type else {}
    request = urllib.request.Request(peer_url(server.peer, path), data=data, headers=headers)
    try:
        return open_direct(request, timeout)
    except urllib.error.HTTPError as err:
        err.close()
        raise


def peer_json(server, path, timeout, data=None, content_type=None):
    with open_peer(server, path, timeout, data, content_type) as response:
        if response.headers.get_content_type() != "application/json":
            raise ValueError("Unexpected peer metadata type")
        raw = response.read(MAX_PEER_METADATA + 1)
    if len(raw) > MAX_PEER_METADATA:
        raise ValueError("Peer metadata exceeds the limit")
    try:
        result = json.loads(raw.decode("utf-8"))
    except RecursionError as err:
        raise ValueError("Invalid peer metadata") from err
    if not isinstance(result, dict):
        raise ValueError("Invalid peer metadata")
    return result


def peer_text(value, limit):
    if not isinstance(value, str):
        return ""
    return flat("".join(c if c.isprintable() else " " for c in value[:limit * 2]), limit)


def legacy_device_role(name):
    return "handheld" if re.search(r"\b(?:legion go|handheld)\b", name, re.I) else "pc"


def peer_models(server):
    models = peer_json(server, "/peer/ai", 2).get("brains")
    if not isinstance(models, list):
        raise ValueError("Invalid peer model list")
    found = []
    for entry in models[:4]:
        if not isinstance(entry, dict) or entry.get("up") is not True:
            continue
        model = peer_text(entry.get("model"), 128)
        if not model or entry.get("id") != "local:" + model:
            continue
        where = peer_text(entry.get("where"), 80) or "the other machine"
        label = peer_text(entry.get("label"), 160) or f"{model} on {where}"
        role = entry.get("role")
        if role not in ("pc", "handheld"):
            role = legacy_device_role(where + " " + label)
        found.append({"id": "peer:local:" + model, "model": model, "where": where, "label": label, "role": role, "up": True})
    return found


def brains(server, local_only=False):
    """Every place an answer can come from: each model on this machine, and each one on the peer machine if it is reachable.

    The first brain in the list is the one "auto" uses: the peer's first (the big machine) when it is up, else this machine's.
    """
    here, names = [], local_models()
    role = getattr(server, "device_role", "pc")
    for name in (names or [])[:4]:
        here.append({"id": "local:" + name, "model": name, "where": server.where, "label": f"{name} on {server.where}", "role": role, "up": True})
    here.sort(key=lambda b: b["model"] != server.model)                    # the model named with --model comes first
    there = []
    if server.peer and not local_only:
        try:
            there = peer_models(server)
            if not there:
                there.append({"id": "peer", "model": "", "where": "the other machine", "label": "the other machine has no model ready", "up": False})
        except PEER_ERRORS:
            there.append({"id": "peer", "model": "", "where": "the other machine", "label": "the other machine cannot be reached", "up": False})
    return there + here


