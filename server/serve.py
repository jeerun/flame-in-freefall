def ask_model(model, system, user):
    """Yield the answer piece by piece. Thinking output, if the model produces any, is dropped."""
    body = {"model": model, "stream": True, "think": False, "keep_alive": "30m",
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
            "options": {"temperature": 0.2, "seed": 7, "num_ctx": 8192, "num_predict": 420}}
    for attempt in (1, 2):
        req = urllib.request.Request(OLLAMA + "/api/chat", data=json.dumps(body).encode("utf-8"),
                                     headers={"Content-Type": "application/json"})
        try:
            resp = open_direct(req, 180)
            break
        except urllib.error.HTTPError as err:
            detail = err.read().decode("utf-8", "replace")
            if attempt == 1 and "think" in detail.lower():
                body.pop("think")                          # this model has no thinking switch
                continue
            raise RuntimeError(f"Ollama answered {err.code}: {detail[:200]}")
    with resp:
        for raw in resp:
            if not raw.strip():
                continue
            event = json.loads(raw)
            piece = (event.get("message") or {}).get("content") or ""
            if piece:
                yield piece
            if event.get("done"):
                break


def warm_up(server, model):
    """Load the model into memory before the first real question (a cold start can take a minute)."""
    started = time.time()
    try:
        with server.one_at_a_time:
            "".join(ask_model(model, SYSTEM, "QUESTION: Reply with the single word ready.\n\nMATERIAL\nnone"))
        print(f"Local AI warmed up in {time.time() - started:.0f} s. First answers will be quick now.")
    except (OSError, RuntimeError, ValueError) as err:
        print(f"Local AI warm-up failed: {err}")


class Server(ThreadingHTTPServer):
    allow_reuse_address = os.name != "nt"              # on Windows, reuse would let two servers share one port
    export_lock = threading.Lock()                    # Windows cannot replace a file while another request has it open
    max_handlers = 32

    def __init__(self, *args, **kwargs):
        self.seen = {}
        self.allowed_devices = frozenset()
        self.public_origin = None
        self.machine_name = socket.gethostname().lower()
        self.admin_password = secrets.token_urlsafe(24)
        self.visitor_lock = threading.Lock()
        self.handler_slots = threading.BoundedSemaphore(self.max_handlers)
        super().__init__(*args, **kwargs)

    def verify_request(self, request, client_address):
        address = ipaddress.ip_address(client_address[0])
        return address.is_loopback or address in self.allowed_devices

    def process_request(self, request, client_address):
        if not self.handler_slots.acquire(blocking=False):
            try:
                request.setblocking(False)
                request.sendall(b"HTTP/1.0 503 Service Unavailable\r\nConnection: close\r\nContent-Length: 0\r\n\r\n")
            except OSError:
                pass
            finally:
                self.shutdown_request(request)
            return
        try:
            super().process_request(request, client_address)
        except Exception:
            self.handler_slots.release()               # worker could not be started
            raise

    def process_request_thread(self, request, client_address):
        try:
            super().process_request_thread(request, client_address)
        finally:
            self.handler_slots.release()


class Handler(BaseHTTPRequestHandler):
    server_version = "FlameConsole/1"
    timeout = 10                                      # idle timeout for a client socket

    def parse_request(self):
        if not super().parse_request():
            return False
        hosts = self.headers.get_all("Host", [])
        if len(hosts) != 1:
            self.send_error(400, "One dashboard host is required")
            return False
        host = hosts[0].lower()
        port = self.server.server_port
        names = {"localhost", self.server.machine_name, self.connection.getsockname()[0]}
        direct = {f"{name}:{port}" for name in names}
        if port == 80:
            direct.update(names)
        proxy_origin = self.server.public_origin if ipaddress.ip_address(self.client_address[0]).is_loopback else None
        proxied_host = proxy_origin and urlsplit(proxy_origin).netloc == host
        if host not in direct and not proxied_host:
            self.send_error(403, "Unknown dashboard host")
            return False
        if self.command != "POST":
            return True
        # Browsers send Origin on cross-origin submissions. Python peers have no browser origin.
        origins = self.headers.get_all("Origin", [])
        permitted = set()
        if host in direct:
            permitted.add("http://" + (host.removesuffix(":80") if port == 80 else host))
        if proxy_origin:
            permitted.add(proxy_origin)
        if origins and (len(origins) != 1 or origins[0].lower() not in permitted):
            self.send_error(403, "Unknown dashboard origin")
            return False
        media = {"/ask": "application/json", "/peer/ask": "application/json",
                 "/export": "text/csv", "/peer/export": "text/csv"}.get(self.path)
        if media and (len(self.headers.get_all("Content-Type", [])) != 1 or self.headers.get_content_type() != media):
            self.send_error(415, "Unexpected media type")
            return False
        return True

    def handle(self):
        try:
            super().handle()
        except (ConnectionError, TimeoutError):
            pass                                           # the browser went away mid-answer: nothing to do

    def log_request(self, code="-", size="-"):
        route = getattr(self, "path", "").partition("?")[0]
        if route not in STATIC and route not in ("/ai", "/ask", "/export", "/who", "/tests.csv",
                                                 "/peer/ai", "/peer/ask", "/peer/export"):
            route = "(unknown route)"
        method = self.command if self.command in ("GET", "POST", "HEAD") else "(unknown method)"
        self.log_message("%s %s %s", method, route, code)

    def log_error(self, fmt, *args):
        # The HTTP parser's error message may contain the original request line.
        self.log_message("HTTP request error")

    def send_json(self, obj, code=200):
        data = json.dumps(obj).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def visitor(self):
        """The device that asked. Behind a proxy on this machine (Tailscale Serve), that is the address the proxy passes on."""
        ip = self.client_address[0]
        if self.server.public_origin and ipaddress.ip_address(ip).is_loopback:
            forwarded = self.headers.get("X-Forwarded-For", "").rsplit(",", 1)[-1].strip()
            try:
                return str(ipaddress.ip_address(forwarded))
            except ValueError:
                pass
        return ip

    def note_visitor(self, path):
        """Remember which devices have asked for something, so the person at the PC can see that the handheld got through."""
        ip, seen = self.visitor(), self.server.seen
        with self.server.visitor_lock:
            new = ip not in seen
            if new and len(seen) >= 256:
                del seen[next(iter(seen))]
            entry = seen.setdefault(ip, {"first": time.strftime("%H:%M:%S"), "requests": 0, "asked_ember": 0, "sent_csv": 0})
            entry["requests"] += 1
            entry["last"] = time.strftime("%H:%M:%S")
            entry["last_path"] = path if path in STATIC or path in ("/ai", "/ask", "/export", "/tests.csv") else "(other)"
            entry["asked_ember"] += path == "/ask"
            entry["sent_csv"] += path == "/export"
        if new and ip not in ("127.0.0.1", "::1"):
            print(f"New device connected: {ip}")

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path == "/who":
            # A local proxy also connects from loopback. Visitor-log metadata never grants admin access.
            if not ipaddress.ip_address(self.client_address[0]).is_loopback or any(
                key in self.headers for key in ("Forwarded", "X-Forwarded-For", "X-Forwarded-Host", "X-Forwarded-Proto")
            ) or self.headers["Host"].split(":")[0].lower() not in ("127.0.0.1", "localhost"):
                return self.send_error(404)
            expected = b"Basic " + base64.b64encode(("crew:" + self.server.admin_password).encode("ascii"))
            supplied = self.headers.get("Authorization", "").encode("latin-1")
            if not hmac.compare_digest(supplied, expected):
                self.send_response(401)
                self.send_header("WWW-Authenticate", 'Basic realm="Local device log"')
                self.send_header("Cache-Control", "no-store")
                self.send_header("Content-Length", "0")
                return self.end_headers()
            with self.server.visitor_lock:
                devices = {ip: record.copy() for ip, record in self.server.seen.items()}
            return self.send_json({"this_machine": self.server.host, "devices": devices})
        self.note_visitor(path)
        if path == "/lab/status":
            return self.send_json({"table": True, "film": True})
        if path in ("/ai", "/peer/ai"):
            return self.send_json(ai_status(self.server, local_only=path == "/peer/ai"))
        if path == "/favicon.ico":                         # browsers ask for one; there is none
            self.send_response(204)
            self.send_header("Content-Length", "0")
            return self.end_headers()
        if path == "/tests.csv":
            file = self.server.exports / CSV_NAME
            try:
                with self.server.export_lock, file.open("rb") as source:
                    data = source.read(MAX_CSV + 1)
            except FileNotFoundError:
                return self.send_error(404, "Nothing has been sent yet. Press Send on the dashboard first.")
            except OSError:
                return self.send_error(500, "The export cannot be read")
            if not is_dashboard_export(data):
                return self.send_error(404, "No verified dashboard export. Press Send on the dashboard.")
            self.send_response(200)
            self.send_header("Content-Type", "text/csv; charset=utf-8")
            self.send_header("Content-Disposition", f'attachment; filename="{CSV_NAME}"')
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            return self.wfile.write(data)
        name = STATIC.get(path)
        file = CONSOLE / name if name else None
        if not file or not file.is_file():
            return self.send_error(404)
        if file.suffix == ".webm":
            return evidence_lab.send_film(self, file)
        data = file.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", TYPES[file.suffix])
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def start_answer(self, label, used, fell_back):
        self.send_response(200)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Cache-Control", "no-store")
        ids = dict.fromkeys(i for i in used if isinstance(i, str) and re.fullmatch(r"PSI-[1-9][0-9]{0,8}", i))
        self.send_header("X-Records-Used", ",".join(list(ids)[:12]))
        self.send_header("X-Brain-Label", (peer_text(label, 160) or "Ember").encode("ascii", "replace").decode("ascii"))
        self.send_header("X-Brain-Fallback", "1" if fell_back else "0")
        self.send_header("Connection", "close")
        self.end_headers()

    def export(self, local_only=False):
        """Keep the page's CSV of real tests on this machine and pass it on to the peer machine, if there is one."""
        try:
            length = int(self.headers.get("Content-Length") or 0)
            if not 0 < length <= MAX_CSV:
                return self.send_error(413)
            data = self.rfile.read(length)
        except ValueError:
            return self.send_error(400)
        if len(data) != length or not is_dashboard_export(data):
            return self.send_error(400, "Only the dashboard's complete FLEX export is accepted")
        server = self.server
        try:
            with server.export_lock:
                store_export(server.exports, data)
        except OSError as err:
            print(f"   could not write into {server.exports}: {err}")
            return self.send_error(500, "The exports folder cannot be written")
        saved, missed = [server.host], False
        folder = server.exports.name or "exports"
        link = f"http://{lan_address() or 'localhost'}:{server.server_address[1]}/tests.csv" if server.lan else None
        if server.peer and not local_only:
            try:
                there = peer_json(server, "/peer/export", 5, data, "text/csv")
                names = there.get("saved")
                if not isinstance(names, list) or len(names) != 1 or not peer_text(names[0], 60):
                    raise ValueError("Unexpected peer export receipt")
                saved.insert(0, peer_text(names[0], 60))
                folder = peer_text(there.get("folder"), 60) or folder
                if isinstance(there.get("link"), str) and there["link"]:
                    link = peer_url(server.peer, "/tests.csv")
            except PEER_ERRORS:
                missed = True
        print(f"   kept {len(data.splitlines()) - 1} tests in {server.exports / CSV_NAME}" + (" (the other machine did not take it)" if missed else ""))
        self.send_json({"saved": saved, "folder": folder, "peer_missed": missed, "link": link})

    def do_POST(self):
        self.note_visitor(self.path)
        if self.path in evidence_lab.POST_ROUTES:
            return evidence_lab.handle_request(self, OLLAMA)
        if self.path in ("/export", "/peer/export"):
            return self.export(local_only=self.path == "/peer/export")
        if self.path not in ("/ask", "/peer/ask"):
            return self.send_error(404)
        try:
            length = int(self.headers.get("Content-Length") or 0)
            if not 0 < length <= MAX_BODY:
                return self.send_error(413)
            raw = self.rfile.read(length)
            if len(raw) != length:
                return self.send_error(400, "Incomplete request")
            ask = json.loads(raw.decode("utf-8"))
            if not isinstance(ask, dict):
                return self.send_error(400)
            require_brain = ask.get("require_brain", False)
            if not isinstance(require_brain, bool):
                return self.send_error(400, "Expected a boolean for require_brain")
            ask = {key: ask[key] for key in ("question", "page", "reading", "selected", "need", "brain")
                   if ask.get(key) is not None}
            if any(not isinstance(value, str) for value in ask.values()):
                return self.send_error(400, "Expected text fields")
            question = flat(ask.get("question"), 400)
            if not question:
                return self.send_error(400)
        except (ValueError, RecursionError):
            return self.send_error(400)

        server, found = self.server, brains(self.server, local_only=self.path == "/peer/ask")
        up = [b for b in found if b["up"]]
        wanted = str(ask.get("brain") or "auto")
        require_brain = require_brain and wanted != "auto"
        brain = next((b for b in up if b["id"] == wanted), None)
        if require_brain and not brain:
            return self.send_error(503, "The selected model is offline. Reconnect its device or select Auto.")
        brain = brain or (up[0] if up else None)
        if not brain:
            return self.send_error(503, "No model is ready")
        fell_back = wanted not in ("auto", brain["id"])
        started, count = time.time(), 0

        # The peer endpoint handles this question locally. If the peer is unavailable, try our local model.
        if brain["id"].startswith("peer:"):
            fwd = {"question": question, "brain": brain["id"][len("peer:"):]}
            if require_brain:
                fwd["require_brain"] = True
            if ask.get("page") == "console":
                fwd.update(page="console", reading=str(ask.get("reading") or "")[:4000])
            else:
                fwd.update(page="research", selected=flat(ask.get("selected"), 12), need=flat(ask.get("need"), 20))
            try:
                resp = open_peer(server, "/peer/ask", 20, json.dumps(fwd, ensure_ascii=False).encode("utf-8"), "application/json")
                if resp.headers.get_content_type() != "text/plain":
                    resp.close()
                    raise ValueError("Unexpected peer answer format")
            except PEER_ERRORS as err:
                if require_brain:
                    return self.send_error(503, "The selected device could not answer. Reconnect it or select Auto.")
                mine = next((b for b in up if b["id"].startswith("local:")), None)
                print(f"   the other machine did not answer ({err.__class__.__name__}); " + ("answering here" if mine else "no model here either"))
                if not mine:
                    return self.send_error(503, "The other machine did not answer")
                brain, fell_back = mine, True
            else:
                with resp:
                    if require_brain and resp.headers.get("X-Brain-Fallback") == "1":
                        return self.send_error(503, "The selected device's model is offline. Reconnect it or select Auto.")
                    label = peer_text(resp.headers.get("X-Brain-Label"), 160) or brain["label"]
                    catalogue = {r["id"] for r in server.records}
                    sent_ids = (resp.headers.get("X-Records-Used") or "")[:256].split(",")
                    used = [i.strip() for i in sent_ids if i.strip() in catalogue]
                    self.start_answer(label, used, fell_back or resp.headers.get("X-Brain-Fallback") == "1")
                    deadline = time.monotonic() + 180
                    try:
                        while time.monotonic() < deadline:
                            remaining = MAX_PEER_ANSWER - count
                            chunk = resp.read1(min(4096, remaining + 1))
                            if not chunk:
                                break
                            written = self.wfile.write(chunk[:remaining])
                            self.wfile.flush()
                            count += written
                            if len(chunk) > remaining:
                                self.wfile.write(b"\n[The other machine's answer exceeded the size limit.]")
                                break
                        else:
                            self.wfile.write(b"\n[The other machine's answer exceeded the time limit.]")
                    except (OSError, http.client.HTTPException) as err:
                        try:
                            self.wfile.write(f"\n[The other machine stopped answering: {err.__class__.__name__}]".encode("utf-8"))
                        except OSError:
                            pass
                print(f"   Ember peer request: {count} bytes in {time.time() - started:.1f} s")
                self.close_connection = True
                return

        if not server.one_at_a_time.acquire(blocking=False):
            return self.send_error(503, "Ember is busy. Try again in a moment.")
        try:
            if ask.get("page") == "console":
                material, used = reading_material(server.records, str(ask.get("reading") or ""))
                system = SYSTEM + SYSTEM_READING
            else:
                material, used = research_material(server.records, question, flat(ask.get("selected"), 12), flat(ask.get("need"), 20))
                system = SYSTEM
            user = f"QUESTION: {question}\n\nMATERIAL\n{material}"
            self.start_answer(brain["label"], used, fell_back)
            try:
                for piece in ask_model(brain["model"], system, user):
                    self.wfile.write(piece.encode("utf-8"))
                    self.wfile.flush()
                    count += len(piece)
            except (OSError, RuntimeError, ValueError):
                try:
                    self.wfile.write(b"\n[The model could not finish this answer.]")
                except OSError:
                    pass
        finally:
            server.one_at_a_time.release()
        print(f"   Ember local request: {count} chars in {time.time() - started:.1f} s")
        self.close_connection = True


def lan_address():
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(("10.255.255.255", 1))               # no packet is sent; this only picks the outgoing interface
            return s.getsockname()[0]
    except OSError:
        return None


def tailscale_address(addresses=None):
    """This machine's address on a Tailscale network, if it is on one (Tailscale hands out 100.64.0.0/10)."""
    try:
        found = addresses if addresses is not None else [a[4][0] for a in socket.getaddrinfo(socket.gethostname(), None, socket.AF_INET)]
    except OSError:
        return None
    net = ipaddress.ip_network("100.64.0.0/10")
    return next((a for a in found if ipaddress.ip_address(a) in net), None)


