"""Build the Moon evidence check from the same nine PSI tables as the oxygen map.

Run with: py data/clean/build_moon_evidence.py
"""
import csv
import io
import json
import math

if __package__:
    from . import build_tables as tables
else:
    import build_tables as tables


OUTPUT = tables.ROOT / "console" / "moon-evidence-data.js"
MATERIALS = {"gas flames": "Gas flames", "liquid droplets": "Liquid fuel droplets",
             "solid materials": "Solid materials"}
# The four tables with ambient oxygen and pressure identify tests using these headers.
TEST_COLUMNS = {"FLEX": "FLEX Test #", "CFI": "Flex Number",
                "CFI-G, normal flames": "Test", "Flame Design, normal flames": "Test"}


def records(path):
    """Yield the physical line span as well as the cells of each nonblank CSV record."""
    raw = path.read_bytes()
    try:
        source = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        source = raw.decode("cp1252")
    reader = csv.reader(io.StringIO(source, newline=""))
    start = 1
    for cells in reader:
        end = reader.line_num
        if any(cell.strip() for cell in cells):
            yield start, end, cells
        start = end + 1


def quantity(cell, unit=""):
    value = cell.strip()
    if unit and value.endswith(unit):
        value = value[:-len(unit)].strip()
    try:
        number = float(value)
    except ValueError:
        return None
    return number if math.isfinite(number) else None


def build():
    manifest = json.loads((tables.RAW / "MANIFEST.json").read_text(encoding="utf-8"))
    result = {"thresholds": {"oxygenPct": tables.MOON_O2, "pressurePsi": tables.MOON_PSI},
              "eligible": 0, "tables": [], "matches": []}
    for filename, name, material, oxy, oxy_unit, pressure, p_unit, meaning in tables.SOURCES:
        rows = records(tables.RAW / filename)
        headers = [cell.strip() for cell in next(rows)[2]]
        oi = tables.column(headers, oxy)
        pi = tables.column(headers, pressure) if pressure else None
        source = manifest[filename]
        table = {"file": filename, "id": source["investigation"], "name": name,
                 "doi": source["doi"], "material": MATERIALS[material], "oxygenKind": meaning,
                 "oxygenColumn": headers[oi], "oxygenUnit": oxy_unit,
                 "pressureColumn": headers[pi] if pi is not None else None, "pressureUnit": p_unit,
                 # These nine schemas have no measured gravity field per test. SAFFIRE-II
                 # has separate burn-length outcomes for two gravity settings.
                 "gravityColumn": None, "rows": 0, "eligible": 0, "matches": 0}
        table_index = len(result["tables"])
        result["tables"].append(table)
        for start, end, cells in rows:
            table["rows"] += 1
            if meaning != "ambient" or pi is None or len(cells) <= max(oi, pi):
                continue
            oxygen = quantity(cells[oi])
            p = quantity(cells[pi], p_unit)
            if oxygen is None or p is None or p <= 0:
                continue
            oxygen_pct = oxygen * 100 if oxy_unit == "fraction" else oxygen
            if not 0 < oxygen_pct <= 100:
                continue
            pressure_psi = p * 14.696 / {"mmHg": tables.MMHG, "bar": tables.BAR, "atm": 1}[p_unit]
            table["eligible"] += 1
            if oxygen_pct < tables.MOON_O2 or pressure_psi > tables.MOON_PSI:
                continue
            result["matches"].append({
                "table": table_index, "line": start, "endLine": end,
                "test": cells[tables.column(headers, TEST_COLUMNS[name])].strip(),
                "fuel": cells[tables.column(headers, "Fuel")].strip(),
                "oxygenRaw": cells[oi], "pressureRaw": cells[pi],
                "oxygenPct": round(oxygen_pct, 8), "pressurePsi": round(pressure_psi, 8),
            })
            table["matches"] += 1
        result["eligible"] += table["eligible"]
    return result


def render(data):
    return ("// Generated by data/clean/build_moon_evidence.py from the NASA PSI tables.\n"
            + "window.FLAME_MOON_EVIDENCE = " + json.dumps(data, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    evidence = build()
    OUTPUT.write_text(render(evidence), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.name}: {len(evidence['matches'])} matches in {evidence['eligible']} "
          f"comparable rows across {len(evidence['tables'])} mapped tables.")
