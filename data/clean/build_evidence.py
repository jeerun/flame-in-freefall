"""Export selected SAFFIRE-II and BASS-II measurements for the two offline reveals."""
import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw" / "psi_tables"
GRAVITY = "PSI-99_Experimental table_SAFFIRE-2.csv"
SENSORS = "PSI-25_Experimental table_BASS-II.csv"


def selected_rows(filename, key, identifiers):
    result = {}
    with (RAW / filename).open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source)
        reader.fieldnames = [" ".join(field.split()) for field in reader.fieldnames]
        for row in reader:
            identifier = row[key].strip()
            if identifier in identifiers:
                if identifier in result:
                    raise ValueError(f"Duplicate case {identifier} in {filename}")
                result[identifier] = (identifier, reader.line_num, row)
    return [result[identifier] for identifier in identifiers]


def build():
    manifest = json.loads((RAW / "MANIFEST.json").read_text(encoding="utf-8"))
    data = {}
    for mode, filename in (("gravity", GRAVITY), ("sensors", SENSORS)):
        source = manifest[filename]
        data[mode] = {"source": source["investigation"], "doi": source["doi"], "cases": []}

    for identifier, line, row in selected_rows(GRAVITY, "Sample Number", ("2-2", "2-5", "2-3", "2-1")):
        data["gravity"]["cases"].append({
            "id": identifier, "line": line, "material": row["Material"],
            "length": row["Sample Length"], "oxygen": row["Percent O2 (Note 1)"],
            "flow": row["Air Flow (cm/s)"], "direction": row["Flow Direction"],
            "earth": row["1-g Burn Length"], "orbit": row["?-g Burn Length"],
        })

    for identifier, line, row in selected_rows(SENSORS, "Test #", ("B18", "T2", "F2", "B17")):
        data["sensors"]["cases"].append({
            "id": identifier, "line": line, "material": " ".join(row["Fuel Sample Material"].split()),
            "oxygen": [row["Calibrated initial O2 % by vol"], row["Calibrated final O2 % by vol"]],
            "co": [row["Initial CO (ppm)"], row["Final CO (ppm)"]],
            "co2": [row["Initial CO2 % by vol"], row["Final CO2 % by vol"]],
        })
    return data


if __name__ == "__main__":
    evidence = build()
    output = ROOT / "console" / "evidence-data.js"
    output.write_text("// Generated by data/clean/build_evidence.py from the NASA PSI tables.\n"
                      + "window.FLAME_EVIDENCE_DATA = " + json.dumps(evidence, ensure_ascii=False, indent=2)
                      + ";\n", encoding="utf-8", newline="\n")
    print(f"Wrote {output.name}: {len(evidence['gravity']['cases'])} SAFFIRE-II cases, "
          f"{len(evidence['sensors']['cases'])} BASS-II cases.")
