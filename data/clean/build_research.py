"""Build console/research.js for the NASA research page of the console.

Run from the repo root:  python data/clean/build_research.py
Needs only the Python standard library. Nothing in data/raw is modified.

It joins two files:
  data/raw/psi_search/combustion_investigations.json   facts, exactly as the NASA PSI search returned them
  data/clean/research_notes.json                        plain-language notes and relevance scores (AI-written)
Titles, project type, platform, hardware and dates come from PSI. Summaries and scores come from the notes.
The script stops if a combustion investigation in the PSI file has no note, or a note has no PSI record.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw" / "psi_search" / "combustion_investigations.json"
NOTES = ROOT / "data" / "clean" / "research_notes.json"
OUT = ROOT / "console" / "research.js"
RETRIEVED = "Nov 14, 2026"


def flat(text):
    return re.sub(r"\s+", " ", str(text or "")).strip()


def year(text):
    m = re.search(r"(\d{4})\s*$", flat(text))
    return int(m.group(1)) if m else None


def main():
    hits = {h["_source"]["Accession"]: h["_source"] for h in json.loads(RAW.read_text(encoding="utf-8"))["hits"]["hits"]}
    notes_file = json.loads(NOTES.read_text(encoding="utf-8"))
    notes, excluded, needs = notes_file["notes"], notes_file["excluded"], notes_file["needs"]

    missing = [a for a, s in hits.items() if flat(s.get("Research Area")) == "Combustion Science" and a not in notes]
    unknown = [a for a in list(notes) + list(excluded) if a not in hits]
    stray = [a for a in hits if a not in notes and a not in excluded]
    if missing or unknown or stray:
        raise SystemExit(f"notes out of step with PSI. no note: {missing}; not in PSI file: {unknown}; unaccounted: {stray}")

    items = []
    for acc, n in notes.items():
        s = hits[acc]
        if set(n["scores"]) != {k["key"] for k in needs} or not all(0 <= v <= 3 for v in n["scores"].values()):
            raise SystemExit(f"{acc}: scores must cover every need with 0 to 3")
        hardware = s.get("Experiment Hardware") or {}
        items.append({
            "id": acc,
            "num": int(acc.split("-")[1]),
            "name": n["name"],
            "title": flat(s.get("Title")),
            "type": flat(s.get("Project Type")),
            "platform": flat(s.get("Flight Platform")),
            "area": flat(s.get("SubResearch Area")),
            "hardware": flat(hardware.get("Name") if isinstance(hardware, dict) else hardware),
            "start": year(s.get("Investigation Start Date")),
            "end": year(s.get("Investigation End Date")),
            "related": flat(s.get("Related Investigations")).split(),
            "fuel": n["fuel"],
            "summary": n["summary"],
            "varied": n["varied"],
            "why": n["why"],
            "scores": n["scores"],
        })
    items.sort(key=lambda x: x["num"])

    out = {
        "meta": {
            "source": "NASA PSI data repository, search for \"combustion\"",
            "retrieved": RETRIEVED,
            "returned": len(hits),
            "shown": len(items),
            "excluded": len(excluded),
            "url": "psi.nasa.gov/physci/repo/data/investigations/",
        },
        "needs": needs,
        "items": items,
    }
    OUT.write_text(
        "// Generated by data/clean/build_research.py from the NASA PSI search result and research_notes.json.\n"
        "// Do not edit by hand.\n"
        "window.FLAME_RESEARCH = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    for need in needs:
        ranked = sorted((i for i in items if i["scores"][need["key"]] > 0),
                        key=lambda i: (-i["scores"][need["key"]], i["type"] != "Microgravity Investigation", i["num"]))
        print(f"{need['label']}: " + ", ".join(f"{i['name']} ({i['scores'][need['key']]})" for i in ranked))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(items)} investigations, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
